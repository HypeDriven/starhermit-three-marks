  for (const m of moves) p += `until 600 =Your move\nframes 40\ntouch =${m.name}\nframes 10\n`;
  p += `until 900 =Lesson Complete\nframes 20\n`;
  if (li === 0) p += `save tm-phone-lesson-done\n`;
  const next = LESSONS[li + 1];
  p += next ? `touch =Next: ${next.name}\nframes 20\n` : `save tm-phone-lessons-all\ntouch =Start playing\nuntil 300 Choose a Mode\nframes 10\n`;

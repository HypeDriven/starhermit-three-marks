// Writes the play scripts that play whole matches and lessons
// (tests/native/journey.play, tests/native/learn-phone.play) by running the
// real session (js/session.js) in node with the AI answering at once: the
// rival's moves depend only on the position and its seeded stream, so the
// human moves found here (an Expert search on the player's side, or the cell
// a lesson step asks for) replay exactly on the runtime. The scripts click
// (desktop) or touch (phone) the board mirror's named cells and wait for the
// turn banner between moves. Run after content or AI changes: node tools/gen-plays.mjs
import { writeFileSync } from 'node:fs';
import { GameSession, PHASE } from '../js/session.js';
import { Store } from '../js/storage.js';
import { JOURNEY_STAGES, LESSONS } from '../js/content.js';
import { PracticeAI } from '../js/ai.js';
import { STRINGS } from '../js/strings.js';

const en = STRINGS['en-US'];
const fill = (s, v) => s.replace(/\{(\w+)\}/g, (_, k) => v[k]);
function fakeTimers() {
  const list = []; let id = 1;
  return {
    list,
    setTimeout: (fn, ms) => { list.push({ id, fn, ms }); return id++; },
    clearTimeout: (i) => { const k = list.findIndex((t) => t.id === i); if (k >= 0) list.splice(k, 1); },
    setInterval: () => id++, clearInterval: () => {},
    flush() { for (let g = 0; g < 50 && list.length; g++) list.shift().fn(); },
  };
}
function cellName(state, cell) {
  const n = state.config.boardSize;
  return fill(en.cellLabel, { r: Math.floor(cell / n) + 1, c: (cell % n) + 1, what: en.cellEmpty, avail: en.cellAvailable });
}
function makeSession() {
  const timers = fakeTimers();
  const store = new Store('gen');
  store.persistent = false;
  const s = new GameSession({ platform: { serverNow: () => 0 }, store, audio: null, timers });
  return { s, timers };
}

// ---- Journey stage 1 against the casual rival, to Victory
function journeyMoves() {
  const { s, timers } = makeSession();
  const stage = JOURNEY_STAGES[0];
  s.startMatch({ mode: 'journey', contentId: stage.id, contentName: stage.name, config: stage.config, seed: stage.seed, ai: stage.opponent.difficulty,
    humanPlayer: stage.humanPlayer, series: stage.series, theme: stage.theme, par: stage.par, goals: stage.goals, ranked: false, assists: {} });
  const me = new PracticeAI('expert', 99);
  const moves = [];
  let result = null;
  s.on('match-end', (r) => { result = r; });
  timers.flush();
  for (let g = 0; g < 20 && !result; g++) {
    if (s.phase === PHASE.ACTIVE && s.state.status === 'active' && s.state.currentPlayer === stage.humanPlayer) {
      const cell = me.chooseCell(s.state, stage.humanPlayer);
      moves.push(cellName(s.state, cell));
      s.placeCell(cell);
    }
    timers.flush();
  }
  if (!result || result.outcome !== 'win') throw new Error('journey stage 1 not won: ' + (result && result.outcome));
  return moves;
}
// ---- Learn: every lesson in order
function lessonMoves() {
  const { s, timers } = makeSession();
  const out = [];
  for (const lesson of LESSONS) {
    s.startLesson(lesson);
    const moves = [];
    let done = false;
    const off = s.on('lesson-complete', () => { done = true; });
    const me = new PracticeAI('expert', 7);
    for (let g = 0; g < 40 && !done; g++) {
      if (s.phase === PHASE.TUTORIAL && s.state.status === 'active' && s.state.currentPlayer === 1 && !s.thinking && !timers.list.length) {
        const step = s.lesson.def.steps[s.lesson.stepIndex];
        const cell = step.require.kind === 'place-cell' ? step.require.cell : me.chooseCell(s.state, 1);
        moves.push({ name: cellName(s.state, cell), step: s.lesson.stepIndex });
        s.lessonPlace(cell);
      }
      timers.flush();
    }
    off();
    if (!done) throw new Error('lesson not completed: ' + lesson.id);
    out.push({ lesson, moves });
  }
  return out;
}

const journey = journeyMoves();
